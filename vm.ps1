<#
.SYNOPSIS
    Windsurf VM Manager - spin up, manage, and snapshot Windsurf IDE VMs on Windows.

.DESCRIPTION
    Wraps Vagrant + VirtualBox to provide a simple CLI for isolated Windsurf IDE
    development environments. Each instance gets its own VM, RDP port, snapshot
    history, and one-or-many shared project folders. Single-project VMs mount
    $ProjectPath at /project (legacy); multi-project VMs mount each selected
    project at /projects/<name>. See USAGE.md for all scenarios.

.USAGE
    vm new <name> [-p spec]     Create a VM (spec = comma-separated aliases/paths)
    vm start <name>             Start VM + open Remote Desktop
    vm stop <name>              Halt VM (state preserved)
    vm list                     List all instances with status + projects
    vm delete <name>            Permanently destroy a VM

    vm snapshot <name> <label>  Save a named snapshot
    vm restore <name> <label>   Restore VM to a snapshot
    vm snapshots <name>         List snapshots for an instance

    vm setup-host               One-time SSH bridge setup (auto-elevates)
    vm ssh <name>               SSH into VM from host terminal
    vm status <name>            Show connectivity + bridge health

.EXAMPLE
    vm new dev-main                           # single project (legacy)
    vm new dev-main -p mkt-tools,windsurf-vms # multi-project from aliases
    vm start dev-main
    vm snapshot dev-main clean-state
    vm restore dev-main clean-state
    vm stop dev-main
#>

param(
    [Parameter(Position=0)] [string] $Command     = "",
    [Parameter(Position=1)] [string] $Name        = "",
    [Parameter(Position=2)] [string] $Label       = "",
    # Project list for `vm new`. Comma-separated aliases from $Projects in
    # vm.config.ps1, and/or absolute Windows paths. See USAGE.md section 3.
    # NOTE: param name is ProjectSpec (not Projects) to avoid shadowing the
    # config hashtable when vm.config.ps1 is dot-sourced below.
    [Alias("p")]
    [string] $ProjectSpec = ""
)

