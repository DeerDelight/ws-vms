# --- Commands -----------------------------------------------------------------
switch ($Command.ToLower()) {

    "new" {
        Assert-Name
        Assert-Prerequisites
        if (-not (Test-InstanceName $Name)) { exit 1 }
        Ensure-Config

        $reg      = Get-Registry
        $existing = Get-Instance $reg $Name

        if ($existing) {
            if ($existing.status -in @("error", "provisioning")) {
                $resumeReason = if ($existing.status -eq "error") { "previously failed to provision" } else { "interrupted mid-provision" }
                Write-Warn "Instance '$Name' was $resumeReason. Resuming..."
                $exitCode = Invoke-Vagrant $Name $existing.rdp_port @("up", "--provision")
                $reg = Get-Registry
                $reg.instances.$Name.status = if ($exitCode -eq 0) { "ready" } else { "error" }
                Save-Registry $reg
                if ($exitCode -eq 0) {
                    Write-Ok "VM '$Name' resume succeeded."
                } else {
                    Write-Err "Resume failed (exit $exitCode). See instances/$Name/last-run.log"
                    exit 1
                }
                exit 0
            }
            Write-Warn "Instance '$Name' already exists (port $($existing.rdp_port))."
            Write-Info "Use 'vm start $Name' to launch it."
            exit 1
        }

        # Resolve project list: either from -p CLI flag or interactive prompt.
        # Bridge mode: skip prompt entirely when no -p (browse mode, no shared folders).
        $spec = if (-not [string]::IsNullOrWhiteSpace($ProjectSpec)) {
            $ProjectSpec
        } elseif ($BridgeEnabled) {
            ""   # bridge browse mode: no shared folders needed
        } else {
            Prompt-Projects $Name $Projects
        }
        $resolution = Resolve-Projects $spec $Projects
        if (-not $resolution.Success) {
            Write-Err $resolution.Error
            exit 1
        }
        $projectsArr = @($resolution.Projects)

        $port  = Get-NextPort $reg
        $box   = Get-VmBox
        $isNew = $box -eq "ubuntu/jammy64"

        # Allocate host-only IP when bridge is configured
        $vmHostOnlyIP = ""
        if ($BridgeEnabled) {
            $vmHostOnlyIP = Get-NextHostOnlyIP $reg
        }

        Write-Host ""
        Write-Host "  Creating VM '$Name'" -ForegroundColor Cyan
        Write-Host "  RDP port : localhost:$port"
        if ($vmHostOnlyIP) {
            Write-Host "  Bridge   : $vmHostOnlyIP -> host ($($BridgeConfig.host_ip))"
        }
        if ($projectsArr.Count -eq 0 -and $vmHostOnlyIP) {
            Write-Host "  Projects : (bridge browse mode - no shared folders)"
        } elseif ($projectsArr.Count -eq 0) {
            Write-Host "  Projects : (legacy) $ProjectPath -> /project"
        } else {
            Write-Host "  Projects :"
            foreach ($p in $projectsArr) {
                Write-Host ("               {0,-16} -> {1,-40} -> /projects/{0}" -f $p.name, $p.host_path)
            }
        }
        Write-Host "  RAM      : $([math]::Round($VmRam/1024, 0)) GB  |  CPU: $VmCpus cores  |  Disk: $VmDiskGB GB"
        Write-Host "  Box      : $box"
        Write-Host ""
        if ($isNew) {
            Write-Warn "First run: downloads Ubuntu box (~700 MB) + provisions (~15 min)."
        } else {
            Write-Info "Using pre-built windsurf-base box - VM ready in ~1-2 min."
        }
        Write-Host ""

        # Registry entry: only include `projects` field when multi-project. VMs
        # without the field are treated as legacy by Get-InstanceProjects.
        $newEntry = [PSCustomObject]@{
            rdp_port = $port
            created  = (Get-Date).ToString("yyyy-MM-dd HH:mm")
            status   = "provisioning"
        }
        if ($projectsArr.Count -gt 0) {
            $newEntry | Add-Member -NotePropertyName "projects" -NotePropertyValue $projectsArr
        }
        if ($vmHostOnlyIP) {
            $newEntry | Add-Member -NotePropertyName "host_only_ip" -NotePropertyValue $vmHostOnlyIP
        }
        $reg.instances | Add-Member -NotePropertyName $Name -NotePropertyValue $newEntry
        Save-Registry $reg

        $exitCode = Invoke-Vagrant $Name $port @("up") $projectsArr

        if ($exitCode -eq 0) {
            $reg = Get-Registry
            $reg.instances.$Name.status = "ready"
            Save-Registry $reg

            Write-Host ""
            Write-Ok "VM '$Name' is ready!"
            Write-Host "  Run: vm start $Name" -ForegroundColor Gray
        } else {
            Write-Err "Provisioning failed (exit $exitCode). Check output above."
            $reg = Get-Registry
            $reg.instances.$Name.status = "error"
            Save-Registry $reg
            exit 1
        }
    }

    "start" {
        Assert-Name
        Assert-Prerequisites
        Ensure-Config

        $reg      = Get-Registry
        $instance = Get-Instance $reg $Name

        if (-not $instance) {
            Write-Err "Instance '$Name' not found."
            Write-Info "Use 'vm new $Name' to create it, or 'vm list' to see all instances."
            exit 1
        }

        $port = $instance.rdp_port
        Write-Host ""
        Write-Info "Starting VM '$Name' (RDP: localhost:$port)..."

        $exitCode = Invoke-Vagrant $Name $port @("up")

        if ($exitCode -ne 0) {
            Write-Err "Failed to start VM (exit $exitCode)."
            exit 1
        }

        Write-Info "Waiting $RdpWaitSec s for RDP service..."
        Start-Sleep $RdpWaitSec

        Write-Info "Opening Remote Desktop..."
        Start-Process "mstsc" "/v:localhost:$port"

        $reg = Get-Registry
        $reg.instances.$Name.status = "running"
        Save-Registry $reg

        $projSummary = Format-ProjectSummary $instance
        $hasBridge = $instance.PSObject.Properties["host_only_ip"]
        $projLabel = if ((Get-InstanceProjects $instance).Count -eq 0 -and $hasBridge) {
            "(browse mode - no shared folders)"
        } elseif ((Get-InstanceProjects $instance).Count -eq 0) {
            "/project  (shared folder)"
        } else {
            "$projSummary  (mounted under /projects/)"
        }

        # Bridge status
        $bridgeLabel = ""
        if ($instance.PSObject.Properties["host_only_ip"]) {
            $hostIpDisplay = if ($BridgeConfig) { $BridgeConfig.host_ip } else { "192.168.56.1" }
            $bridgeLabel = "Remote-SSH auto-connects to host ($($instance.host_only_ip) -> $hostIpDisplay)"
        }

        Write-Host ""
        Write-Ok "Connected to '$Name'"
        Write-Host "  Login    : vagrant / vagrant" -ForegroundColor Gray
        Write-Host "  Projects : $projLabel" -ForegroundColor Gray
        if ($bridgeLabel) {
            Write-Host "  Bridge   : $bridgeLabel" -ForegroundColor Gray
            $winHome = if ($HostUser) { "C:\Users\$HostUser" } else { "Windows home" }
            Write-Host "  Windsurf : auto-opens $winHome via Remote-SSH" -ForegroundColor Gray
        } else {
            Write-Host "  Windsurf : launches from application menu" -ForegroundColor Gray
        }
        Write-Host ""
    }

    "stop" {
        Assert-Name
        Assert-Prerequisites
        $reg      = Get-Registry
        $instance = Get-Instance $reg $Name

        if (-not $instance) {
            Write-Err "Instance '$Name' not found."
            exit 1
        }

        Write-Info "Stopping VM '$Name'..."
        $exitCode = Invoke-Vagrant $Name $instance.rdp_port @("halt")

        $reg = Get-Registry
        if ($exitCode -eq 0) {
            $reg.instances.$Name.status = "stopped"
            Save-Registry $reg
            Write-Ok "VM '$Name' stopped. State preserved - 'vm start $Name' to resume."
        } else {
            Write-Warn "vagrant halt returned error (exit $exitCode). VM may still be running."
            Write-Info "Check status: vm list"
        }
    }

    "list" {
        $reg = Get-Registry
        Write-Host ""
        Write-Host "  Windsurf VM Instances" -ForegroundColor Cyan
        Write-Host "  ---------------------------------------------------------" -ForegroundColor DarkGray

        $props = $reg.instances.PSObject.Properties
        if ($props.Count -eq 0) {
            Write-Host "  (no instances)  Use: vm new <name>" -ForegroundColor DarkGray
        } else {
            # Reconcile registry state against actual VirtualBox state so that
            # externally-halted VMs aren't shown as 'running'.
            $running   = Get-VBoxRunningVMs
            $regDirty  = $false
            foreach ($prop in $props) {
                $inst   = $prop.Value
                $vboxName = "windsurf-$($prop.Name)"
                $actual = if ($running.ContainsKey($vboxName)) { "running" } else { $inst.status }
                # Drift detection: registry says running, VBox says not.
                if ($inst.status -eq "running" -and -not $running.ContainsKey($vboxName)) {
                    $inst.status = "stopped"
                    $actual = "stopped"
                    $regDirty = $true
                }
                $status = $actual
                $color  = switch ($status) {
                    "running"      { "Green" }
                    "ready"        { "Yellow" }
                    "stopped"      { "DarkGray" }
                    "provisioning" { "Cyan" }
                    "error"        { "Red" }
                    default        { "Gray" }
                }
                $sshInfo = ""
                if ($inst.PSObject.Properties["host_only_ip"]) {
                    $sshInfo = "  SSH: $($inst.host_only_ip)"
                }
                $line = "  {0,-12} RDP: localhost:{1,-5}{2}  [{3}]  Created: {4}" -f `
                    $prop.Name, $inst.rdp_port, $sshInfo, $status, $inst.created
                Write-Host $line -ForegroundColor $color
                $projLine = "               Projects: {0}" -f (Format-ProjectSummary $inst)
                Write-Host $projLine -ForegroundColor DarkGray
                if ($inst.PSObject.Properties["host_only_ip"] -and $status -eq "running") {
                    Write-Host "               Bridge: auto-connected to host" -ForegroundColor DarkGray
                }
            }
            if ($regDirty) { Save-Registry $reg }
        }

        Write-Host "  ---------------------------------------------------------" -ForegroundColor DarkGray
        Write-Host ""
    }

    "delete" {
        Assert-Name
        Assert-Prerequisites
        $reg      = Get-Registry
        $instance = Get-Instance $reg $Name

        if (-not $instance) {
            Write-Err "Instance '$Name' not found."
            exit 1
        }

        Write-Host ""
        Write-Warn "This will PERMANENTLY destroy VM '$Name' and all its snapshots."
        Write-Host "  (Your project files are NOT affected)" -ForegroundColor DarkGray
        $confirm = Read-Host "  Type 'yes' to confirm"

        if ($confirm -ne "yes") {
            Write-Info "Cancelled."
            exit 0
        }

        Write-Info "Destroying VM '$Name'..."
        Invoke-Vagrant $Name $instance.rdp_port @("destroy", "-f") | Out-Null

        $newInstances = [PSCustomObject]@{}
        foreach ($prop in $reg.instances.PSObject.Properties) {
            if ($prop.Name -ne $Name) {
                $newInstances | Add-Member -NotePropertyName $prop.Name -NotePropertyValue $prop.Value
            }
        }
        $reg.instances = $newInstances
        Save-Registry $reg

        $instanceDir = Join-Path $InstancesDir $Name
        Remove-Item -Recurse -Force $instanceDir -ErrorAction SilentlyContinue

        Write-Ok "VM '$Name' deleted."
    }

    "snapshot" {
        Assert-Name
        Assert-Label
        Assert-Prerequisites
        $reg      = Get-Registry
        $instance = Get-Instance $reg $Name

        if (-not $instance) {
            Write-Err "Instance '$Name' not found."
            exit 1
        }

        Write-Info "Saving snapshot '$Label' for '$Name'..."
        Invoke-Vagrant $Name $instance.rdp_port @("snapshot", "save", "--force", $Label)
        Write-Ok "Snapshot '$Label' saved."
    }

    "restore" {
        Assert-Name
        Assert-Label
        Assert-Prerequisites
        $reg      = Get-Registry
        $instance = Get-Instance $reg $Name

        if (-not $instance) {
            Write-Err "Instance '$Name' not found."
            exit 1
        }

        Write-Warn "This will revert '$Name' to snapshot '$Label'. Unsaved VM state will be lost."
        $confirm = Read-Host "  Confirm? (y/N)"
        if ($confirm -ne "y") { Write-Info "Cancelled."; exit 0 }

        Write-Info "Restoring '$Name' to '$Label'..."
        Invoke-Vagrant $Name $instance.rdp_port @("snapshot", "restore", $Label)
        Write-Ok "'$Name' restored to '$Label'."
    }

    "snapshots" {
        Assert-Name
        Assert-Prerequisites
        $reg      = Get-Registry
        $instance = Get-Instance $reg $Name

        if (-not $instance) {
            Write-Err "Instance '$Name' not found."
            exit 1
        }

        Write-Info "Snapshots for '$Name':"
        Invoke-Vagrant $Name $instance.rdp_port @("snapshot", "list")
    }

    "setup-host" {
        Write-Info "Running host SSH bridge setup..."
        $setupScript = Join-Path $RootDir "setup-host-ssh.ps1"
        if (-not (Test-Path $setupScript)) {
            Write-Err "setup-host-ssh.ps1 not found in $RootDir"
            exit 1
        }
        & powershell -NoProfile -ExecutionPolicy Bypass -File $setupScript
        $code = $LASTEXITCODE
        if ($code -ne 0) { exit $code }
    }

    "ssh" {
        Assert-Name
        Assert-Prerequisites
        $reg      = Get-Registry
        $instance = Get-Instance $reg $Name

        if (-not $instance) {
            Write-Err "Instance '$Name' not found."
            exit 1
        }

        # Use vagrant ssh — handles port (incl. auto_correct) and keys automatically.
        $instanceDir = Join-Path $InstancesDir $Name
        $vag = Resolve-Vagrant
        $env:VAGRANT_DOTFILE_PATH = $instanceDir
        $env:VAGRANT_CWD          = $RootDir
        try {
            Write-Info "SSH into '$Name' (via vagrant ssh)..."
            & $vag ssh
            exit $LASTEXITCODE
        } finally {
            Remove-Item Env:VAGRANT_DOTFILE_PATH -ErrorAction SilentlyContinue
            Remove-Item Env:VAGRANT_CWD          -ErrorAction SilentlyContinue
        }
    }

    "status" {
        Assert-Name
        $reg      = Get-Registry
        $instance = Get-Instance $reg $Name

        if (-not $instance) {
            Write-Err "Instance '$Name' not found."
            exit 1
        }

        Write-Host ""
        Write-Host "  VM Status: $Name" -ForegroundColor Cyan
        Write-Host "  ---------------------------------------------------------" -ForegroundColor DarkGray
        Write-Host "  RDP        : localhost:$($instance.rdp_port)"
        Write-Host "  Status     : $($instance.status)"
        Write-Host "  Created    : $($instance.created)"
        Write-Host "  Projects   : $(Format-ProjectSummary $instance)"

        if ($instance.PSObject.Properties["host_only_ip"]) {
            $ip = $instance.host_only_ip
            $hostIp = if ($BridgeConfig) { $BridgeConfig.host_ip } else { "192.168.56.1" }
            Write-Host "  Host-only  : $ip"
            Write-Host "  Bridge to  : $hostIp (user: $HostUser)" 

            # Test SSH connectivity (both directions) if VM appears to be running
            $running2  = Get-VBoxRunningVMs
            $vboxName2 = "windsurf-$Name"
            if ($running2.ContainsKey($vboxName2)) {
                $instanceDir2 = Join-Path $InstancesDir $Name
                $vag2 = Resolve-Vagrant
                if ($vag2) {
                    $env:VAGRANT_DOTFILE_PATH = $instanceDir2
                    $env:VAGRANT_CWD          = $RootDir
                    try {
                        # Test 1: host → VM
                        $vmTest = & $vag2 ssh -c "echo vm_ok" 2>&1 | Out-String
                        Write-Host "  SSH host→VM  : " -NoNewline
                        if ($vmTest -match "vm_ok") {
                            Write-Host "OK" -ForegroundColor Green
                            # Test 2: VM → host (bridge) -- only when bridge configured
                            $bridgeTest = & $vag2 ssh -c `
                                "ssh -o BatchMode=yes -o ConnectTimeout=5 -o StrictHostKeyChecking=accept-new host echo bridge_ok 2>&1" `
                                2>&1 | Out-String
                            Write-Host "  SSH VM→host  : " -NoNewline
                            if ($bridgeTest -match "bridge_ok") {
                                Write-Host "OK  (bridge working)" -ForegroundColor Green
                            } else {
                                Write-Host "FAILED  (run: vm setup-host)" -ForegroundColor Red
                            }
                        } else {
                            Write-Host "FAILED" -ForegroundColor Red
                        }
                    } finally {
                        Remove-Item Env:VAGRANT_DOTFILE_PATH -ErrorAction SilentlyContinue
                        Remove-Item Env:VAGRANT_CWD          -ErrorAction SilentlyContinue
                    }
                }
            }
        } else {
            Write-Host "  Bridge     : not configured"
        }

        Write-Host "  ---------------------------------------------------------" -ForegroundColor DarkGray
        Write-Host ""
    }

    { $_ -in @("", "help", "-h", "--help") } {
        Show-Help
    }

    default {
        Write-Err "Unknown command: '$Command'"
        Show-Help
        exit 1
    }
}